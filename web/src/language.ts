export const STORE_COPY_KEYS = Object.keys(BN).sort((a, b) => a.localeCompare(b));

export function tr(text: string, language: StoreLanguage): string {
  if (!text || typeof text !== 'string') return text;
  const trimmed = text.trim();
  const override = copyOverrides[trimmed]?.[language] || copyOverrides[text]?.[language];
  if (typeof override === 'string' && override.length) return override;

  if (language === 'bn') {
    if (BN[text]) return BN[text];
    if (BN[trimmed]) return text.replace(trimmed, BN[trimmed]);
    
    // Replace known English phrases
    if (/[a-zA-Z]/.test(text)) {
      let res = text;
      for (const enKey of sortedEnKeys) {
        if (enKey.length >= 3 && res.includes(enKey)) {
          res = res.split(enKey).join(BN[enKey]);
        }
      }
      return res;
    }
    return text;
  }

  // language === 'en'
  if (EN_FROM_BN[text]) return EN_FROM_BN[text];
  if (EN_FROM_BN[trimmed]) return text.replace(trimmed, EN_FROM_BN[trimmed]);

  // Strip emojis to test base phrase
  const stripped = trimmed.replace(/^[\p{Emoji}\s•·\-✓✕👁️🔄🛡️⚡📝🚚⚠️📍📋🟢🔴🟡]+|[\p{Emoji}\s•·\-✓✕👁️🔄🛡️⚡📝🚚⚠️📍📋🟢🔴🟡]+$/gu, '').trim();
  if (stripped && EN_FROM_BN[stripped]) {
    return text.replace(stripped, EN_FROM_BN[stripped]);
  }

  // Replace known Bengali phrases if text contains Bengali
  if (/[\u0980-\u09FF]/.test(text)) {
    let res = text;
    for (const bnKey of sortedBnKeys) {
      if (bnKey.length >= 2 && res.includes(bnKey)) {
        res = res.split(bnKey).join(EN_FROM_BN[bnKey]);
      }
    }
    return res;
  }

  return text;
}

